/**
 * Marksage's version, computed from the git history — so anyone can check it, for any commit.
 *   node --experimental-strip-types scripts/version.ts                     # version of HEAD
 *   node --experimental-strip-types scripts/version.ts --commit <ref>      # version of any commit
 *   node --experimental-strip-types scripts/version.ts --list              # every versioned commit
 *   node --experimental-strip-types scripts/version.ts --next "<message>"  # before committing: write package.json
 *                                                                          #   and CHANGELOG.md as that commit will be
 *   node --experimental-strip-types scripts/version.ts --check             # package.json + CHANGELOG.md match HEAD
 *
 * The rule (adopted 2026-10-30; earlier versions were assigned retroactively from the log):
 *   - `feat` → minor (patch back to 0) · `fix`, `perf` → patch · anything else (docs, chore, test, style,
 *     refactor, or a subject that isn't a conventional commit) → no change;
 *   - majors only at the three commits in MAJORS, the product's generations — the one judgment call, listed by hash.
 * Dates are commit dates in America/Sao_Paulo, as everywhere in the project.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const ROOT = new URL('..', import.meta.url).pathname
const MAJORS: Record<string, { major: number; what: string }> = {
  '883a328': { major: 1, what: 'the minimalist Markdown previewer' },
  '899f502': { major: 2, what: 'Smart Assist wired in — the editor that notices (renamed Marksage in 2.4.0)' },
  d724a55: { major: 3, what: 'Marksage’s own trained code-language model ships (later the Rules + AI mode)' },
}

export interface Version {
  hash: string
  date: string
  subject: string
  version: string
  /** Whether this commit changed the version (feat / fix / perf / a major). */
  bumps: boolean
}

const git = (...args: string[]) => execFileSync('git', args, { cwd: ROOT, encoding: 'utf8', env: { ...process.env, TZ: 'America/Sao_Paulo' } })

/** What a commit subject does to the version. */
export function bumpOf(subject: string): 'minor' | 'patch' | null {
  const type = /^([a-z]+)(\([^)]*\))?!?:/.exec(subject)?.[1]
  return type === 'feat' ? 'minor' : type === 'fix' || type === 'perf' ? 'patch' : null
}

/** Every commit up to `ref`, oldest first, with the version it produced. */
export function history(ref = 'HEAD', next?: string): Version[] {
  const rows = git('log', '--reverse', '--format=%H%x09%ad%x09%s', '--date=format-local:%Y-%m-%d', ref)
    .split('\n')
    .filter(Boolean)
    .map((l) => l.split('\t') as [string, string, string])
  if (next) rows.push(['(this commit)', new Date().toLocaleDateString('sv-SE', { timeZone: 'America/Sao_Paulo' }), next])
  let [M, m, p] = [0, 0, 0]
  return rows.map(([hash, date, subject]) => {
    const major = Object.entries(MAJORS).find(([h]) => hash.startsWith(h))?.[1]
    const bump = bumpOf(subject)
    if (major) [M, m, p] = [major.major, 0, 0]
    else if (bump === 'minor') [m, p] = [m + 1, 0]
    else if (bump === 'patch') p++
    return { hash, date, subject, version: `${M}.${m}.${p}`, bumps: !!major || !!bump }
  })
}

export function changelog(versions: Version[]): string {
  const out = [
    '# Changelog',
    '',
    'Every version of Marksage and the commit that made it, newest first — generated by `scripts/version.ts` from the',
    'git history (`--check` verifies this file). `feat` → minor, `fix` / `perf` → patch, other commits don’t change',
    'the version; majors mark the three generations of the product. **Versions before 3.33.3 were assigned',
    'retroactively on 2026-10-30** with this same rule — the commits are unchanged. The story behind them: the',
    'app’s `#story` page and `SMART-ASSIST — Implementation Context.md`. Dates: America/Sao_Paulo.',
    '',
  ]
  const shown = versions.filter((v) => v.bumps)
  for (const major of Object.values(MAJORS).sort((a, b) => b.major - a.major)) {
    const inMajor = shown.filter((v) => v.version.startsWith(`${major.major}.`)).reverse()
    out.push(`## ${major.major}.x — ${major.what}`, '')
    for (const v of inMajor) out.push(`- **${v.version}** · ${v.date} · \`${v.hash.startsWith('(') ? v.hash : v.hash.slice(0, 7)}\` · ${v.subject}`)
    out.push('')
  }
  return out.join('\n')
}

const pkgPath = `${ROOT}package.json`
const logPath = `${ROOT}CHANGELOG.md`
const flag = (n: string) => (process.argv.includes(n) ? process.argv[process.argv.indexOf(n) + 1] : null)

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--list')) {
    for (const v of history().filter((x) => x.bumps)) console.log(`${v.version.padEnd(8)} ${v.date} ${v.hash.slice(0, 7)} ${v.subject}`)
  } else if (process.argv.includes('--next')) {
    const message = flag('--next')
    if (!message) throw new Error('--next needs the commit message')
    const versions = history('HEAD', message.split('\n')[0])
    const now = versions[versions.length - 1]
    const pkg = readFileSync(pkgPath, 'utf8').replace(/"version": "[^"]*"/, `"version": "${now.version}"`)
    writeFileSync(pkgPath, pkg)
    writeFileSync(logPath, changelog(versions))
    console.log(`${now.bumps ? 'version' : 'unchanged'}: ${now.version} — package.json and CHANGELOG.md written (commit them with it)`)
  } else if (process.argv.includes('--check')) {
    const versions = history()
    const head = versions[versions.length - 1]
    const pkgVersion = (JSON.parse(readFileSync(pkgPath, 'utf8')) as { version: string }).version
    // The commit that made a version can't know its own hash: the changelog lists it as "(this commit)".
    const want = changelog(versions)
    const have = readFileSync(logPath, 'utf8').replace(/`\(this commit\)`/, `\`${head.hash.slice(0, 7)}\``)
    const problems = [
      ...(pkgVersion === head.version ? [] : [`package.json says ${pkgVersion}, the history says ${head.version}`]),
      ...(have === want ? [] : ['CHANGELOG.md differs from the history — run --next "<message>" before committing, or regenerate it']),
    ]
    console.log(problems.length ? problems.join('\n') : `ok: ${head.version} (${head.hash.slice(0, 7)})`)
    process.exit(problems.length ? 1 : 0)
  } else {
    const ref = flag('--commit') ?? 'HEAD'
    const v = history(ref)
    console.log(v[v.length - 1].version)
  }
}
